"""Turn the Arena rarity spreadsheet into public/js/arena-tiers.js.

    python tools/arena_tiers.py "path/to/Arena rarity tiers.xlsx"

The workbook has a 'Read me' tab (tier weights in A12:B16) and 'Pokémon' / 'Trainers' tabs with the card id in
column A and the tier in the yellow Tier column. Cards not listed are Common.
"""
import json, sys
from openpyxl import load_workbook

TIERS = ['Common', 'Uncommon', 'Rare', 'Epic', 'Legendary']
LETTER = {'Common': 'C', 'Uncommon': 'U', 'Rare': 'R', 'Epic': 'E', 'Legendary': 'L'}
src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else 'public/js/arena-tiers.js'
cards = {c['id']: c for c in json.load(open('public/cards.json', encoding='utf-8'))['cards']}
wb = load_workbook(src)

weights = {}
for row in wb['Read me'].iter_rows(min_row=1, max_row=40):
    name, w = row[0].value, row[1].value
    if name in TIERS and isinstance(w, (int, float)): weights[name] = w
assert set(weights) == set(TIERS), f'weights missing for {set(TIERS) - set(weights)}'
assert all(w >= 0 for w in weights.values()) and sum(weights.values()) > 0, 'weights must be positive'

tiers, counts, problems = {}, {t: 0 for t in TIERS}, []
for sheet in ('Pokémon', 'Trainers'):
    ws = wb[sheet]
    head = [c.value for c in ws[1]]
    tcol = head.index('Tier')
    for row in ws.iter_rows(min_row=2):
        cid, tier = row[0].value, row[tcol].value
        if not cid: continue
        tier = (tier or '').strip().title()
        if cid not in cards: problems.append(f'{sheet}: unknown card id {cid}'); continue
        if tier not in TIERS: problems.append(f'{sheet}: {cards[cid]["name"]} has tier {row[tcol].value!r}'); continue
        counts[tier] += 1
        if tier != 'Common': tiers[cid] = LETTER[tier]
if problems:
    print('\n'.join(problems)); sys.exit(1)

body = '\n'.join(f"  '{cid}': '{t}', // {cards[cid]['name']}" for cid, t in sorted(tiers.items(), key=lambda kv: ('LERU'.index(kv[1]), cards[kv[0]]['name'])))
js = f"""// Arena rarity tiers. GENERATED by tools/arena_tiers.py from the rarity spreadsheet: edit the spreadsheet, not this file.
// L Legendary, E Epic, R Rare, U Uncommon; any card not listed is Common.
export const TIER_WEIGHTS = {{ C: {weights['Common']}, U: {weights['Uncommon']}, R: {weights['Rare']}, E: {weights['Epic']}, L: {weights['Legendary']} }};
export const TIER_NAMES = {{ C: 'Common', U: 'Uncommon', R: 'Rare', E: 'Epic', L: 'Legendary' }};
export const TIERS = {{
{body}
}};
"""
open(out, 'w', encoding='utf-8', newline='').write(js)
print('weights', weights)
print('cards per tier', counts)
print('wrote', out)
